import { notFound } from "next/navigation";
import { clientIp } from "@/server/audit";
import { headers } from "next/headers";
import { requirePageViewer } from "@/server/pages";
import { ctxOf } from "@/server/services/common";
import { getInvoice } from "@/server/services/sales.service";
import { fmtMoney, fmtDate } from "@/lib/format";

export const dynamic = "force-dynamic";

export default async function PrintInvoicePage({ params }: PageProps<"/print/invoices/[id]">) {
  const { id } = await params;
  const viewer = await requirePageViewer();
  const h = await headers();
  let inv;
  try {
    inv = await getInvoice(ctxOf(viewer, clientIp(h)), id);
  } catch {
    notFound();
  }
  const org = await fetchOrg();
  const symbol = inv.currency.symbol;
  const breakdown = (inv.taxBreakdown as Array<{ name: string; bps: number; baseMinor: number; taxMinor: number }> | null) ?? [];

  return (
    <div className="mx-auto max-w-3xl bg-white p-10 text-zinc-900 print:p-0">
      <div className="mb-8 flex items-start justify-between">
        <div>
          <h1 className="text-2xl font-bold">{org.name}</h1>
          <p className="text-sm text-zinc-500">{[org.addressLine1, org.city, org.state].filter(Boolean).join(", ")}</p>
          {org.gstin && <p className="text-sm text-zinc-500">GSTIN: {org.gstin}</p>}
          {org.email && <p className="text-sm text-zinc-500">{org.email}</p>}
        </div>
        <div className="text-right">
          <p className="text-lg font-semibold uppercase tracking-wide">Invoice</p>
          <p className="font-mono text-sm">{inv.number}</p>
          <p className="text-sm text-zinc-500 capitalize">{inv.status.replace("_", " ")}</p>
        </div>
      </div>

      <div className="mb-8 grid grid-cols-2 gap-8 text-sm">
        <div>
          <p className="mb-1 font-semibold uppercase text-xs text-zinc-400">Billed to</p>
          <p className="font-medium">{inv.client?.name}</p>
          {inv.client?.billingEmail && <p className="text-zinc-600">{inv.client.billingEmail}</p>}
          {inv.client?.gstin && <p className="text-zinc-600">GSTIN: {inv.client.gstin}</p>}
        </div>
        <div className="text-right">
          <p className="text-zinc-600">Issued: {fmtDate(inv.issueDate)}</p>
          <p className="text-zinc-600">Due: {fmtDate(inv.dueDate)}</p>
        </div>
      </div>

      <table className="w-full text-sm">
        <thead>
          <tr className="border-b-2 border-zinc-300 text-left">
            <th className="py-2">Description</th>
            <th className="py-2 text-right">Qty</th>
            <th className="py-2 text-right">Rate</th>
            <th className="py-2 text-right">Amount</th>
          </tr>
        </thead>
        <tbody>
          {inv.lines.map((l) => (
            <tr key={l.id} className="border-b border-zinc-200">
              <td className="py-2">
                <p>{l.description}</p>
                {l.taxBps > 0 && <p className="text-xs text-zinc-400">GST {l.taxBps / 100}%</p>}
              </td>
              <td className="py-2 text-right">{(l.qtyHundredths / 100).toLocaleString("en-IN")}</td>
              <td className="py-2 text-right">{fmtMoney(Number(l.unitPriceMinor), symbol)}</td>
              <td className="py-2 text-right font-medium">{fmtMoney(Number(l.lineTotalMinor), symbol)}</td>
            </tr>
          ))}
        </tbody>
      </table>

      <div className="mt-4 flex justify-end">
        <div className="w-64 space-y-1 text-sm">
          <Sum k="Subtotal" v={fmtMoney(Number(inv.subtotalMinor), symbol)} />
          {breakdown.map((b) => <Sum key={b.name} k={`${b.name} (${b.bps / 100}%)`} v={fmtMoney(b.taxMinor, symbol)} />)}
          {Number(inv.discountMinor) > 0 && <Sum k="Discount" v={`−${fmtMoney(Number(inv.discountMinor), symbol)}`} />}
          <div className="flex justify-between border-t border-zinc-300 pt-1 text-base font-bold">
            <span>Total</span><span>{fmtMoney(Number(inv.totalMinor), symbol)}</span>
          </div>
          {Number(inv.paidMinor) > 0 && <Sum k="Paid" v={fmtMoney(Number(inv.paidMinor), symbol)} />}
        </div>
      </div>

      {inv.terms && (
        <div className="mt-8 text-sm">
          <p className="font-semibold">Terms</p>
          <p className="whitespace-pre-wrap text-zinc-600">{inv.terms}</p>
        </div>
      )}
      <p className="mt-8 text-center text-xs text-zinc-400">Generated by OmniMark</p>
    </div>
  );
}

async function fetchOrg() {
  const { db } = await import("@/server/db");
  const { pageViewer } = await import("@/server/pages");
  const v = await pageViewer();
  return db.organization.findUniqueOrThrow({ where: { id: v!.active!.orgId } });
}

function Sum({ k, v }: { k: string; v: string }) {
  return (
    <div className="flex justify-between">
      <span className="text-zinc-500">{k}</span>
      <span>{v}</span>
    </div>
  );
}
